export class ProseVariationBank {
  constructor({ storage = null, viewerCount = 0, maxSessionCalls = 5, maxGlobalCalls = 20 } = {}) {
    this.storage = storage;
    this.viewerCount = viewerCount;
    this.maxSessionCalls = maxSessionCalls;
    this.maxGlobalCalls = maxGlobalCalls;
    this.sessionCalls = 0;
    this.globalCalls = 0;
    this.cooldowns = new Map();
    this.familyLocks = new Map();
    this.runtimeExpansionCache = new Map();
    this.antiRepetitionMemory = new Set();
    this.recentSentenceHashes = [];
    this.maxMemorySentences = 200;
  }

  setViewerCount(count) {
    this.viewerCount = Math.max(0, Number(count) || 0);
  }

  getViewerCount() {
    return this.viewerCount;
  }

  hasViewers() {
    return this.viewerCount > 0;
  }

  getFamily(familyId) {
    return STATIC_VARIATION_BANK[familyId] || null;
  }

  getAllVariants(familyId) {
    const authored = STATIC_VARIATION_BANK[familyId]?.variants || [];
    const expanded = this.runtimeExpansionCache.get(familyId) || [];
    return [...authored, ...expanded];
  }

  matchesContext(variant, event = {}) {
    if (!variant.conditions) return true;
    const conds = variant.conditions;
    if (conds.weather && event.weather) {
      const w = String(event.weather).toLowerCase();
      if (!conds.weather.some(opt => w.includes(opt.toLowerCase()))) return false;
    }
    if (conds.location && event.location) {
      if (conds.location !== event.location) return false;
    }
    if (conds.participants && Array.isArray(event.participants)) {
      if (!conds.participants.some(p => event.participants.includes(p))) return false;
    }
    return true;
  }

  selectVariant(familyId, event = {}, memory = null) {
    const variants = this.getAllVariants(familyId);
    if (!variants.length) return null;

    const mem = memory || this.antiRepetitionMemory;
    const eligible = variants.filter(v => this.matchesContext(v, event));
    const pool = eligible.length ? eligible : variants;

    // Filter out variants that were used recently (cooldown)
    const fresh = pool.filter(v => !mem.has(v.id));
    let chosen = null;

    if (fresh.length > 0) {
      // Pick the least recently used among fresh variants
      chosen = fresh.reduce((oldest, v) => (v.lastUsedAt < oldest.lastUsedAt ? v : oldest), fresh[0]);
    } else {
      // All eligible variants have been used in recent memory: pick absolute LRU
      chosen = pool.reduce((oldest, v) => (v.lastUsedAt < oldest.lastUsedAt ? v : oldest), pool[0]);
      
      // If active external viewers are present, trigger bounded expansion in background
      if (this.hasViewers() && this.sessionCalls < this.maxSessionCalls) {
        void this.expandFamilyBatch(familyId, event);
      }
    }

    if (chosen) {
      chosen.useCount = (chosen.useCount || 0) + 1;
      chosen.lastUsedAt = event.occurredAt || Date.now();
      mem.add(chosen.id);

      // Keep anti-repetition memory bounded
      if (mem.size > this.maxMemorySentences) {
        const first = mem.values().next().value;
        mem.delete(first);
      }
    }

    return chosen ? chosen.text : null;
  }

  async expandFamilyBatch(familyId, context = {}) {
    // GUARD 1: ZERO VIEWERS = ZERO MODEL CALLS
    if (!this.hasViewers()) {
      return { success: false, reason: 'zero_viewers' };
    }

    // GUARD 2: GLOBAL & SESSION BUDGETS
    if (this.sessionCalls >= this.maxSessionCalls || this.globalCalls >= this.maxGlobalCalls) {
      return { success: false, reason: 'budget_exceeded' };
    }

    // GUARD 3: FAMILY COOLDOWN (1 call per family per hour)
    const now = Date.now();
    if (this.cooldowns.has(familyId) && now < this.cooldowns.get(familyId)) {
      return { success: false, reason: 'family_cooldown' };
    }

    // GUARD 4: SINGLE-FLIGHT LOCK PER FAMILY
    if (this.familyLocks.has(familyId)) {
      return this.familyLocks.get(familyId);
    }

    const promise = (async () => {
      try {
        this.sessionCalls++;
        this.globalCalls++;
        this.cooldowns.set(familyId, now + 3600000);

        // Model call placeholder / simulated LLM expansion hook
        // When real network is available and authorized, fetch from API.
        // If offline or forbidden (e.g. globalThis.fetch throws), graceful fallback occurs.
        const generated = [];
        if (typeof globalThis.fetch === 'function') {
          try {
            // In live viewed session with model API configured
            // fetch batch of 8-20 alternatives
          } catch (err) {
            // Graceful fallback: network or LLM failure does not break story
          }
        }

        // Validate and permanently cache acceptable variants
        if (generated.length) {
          const validated = generated.filter(g => this.validateGeneratedVariant(g, familyId));
          const existing = this.runtimeExpansionCache.get(familyId) || [];
          this.runtimeExpansionCache.set(familyId, [...existing, ...validated]);
        }

        return { success: true, count: generated.length };
      } catch (err) {
        return { success: false, error: err.message };
      } finally {
        this.familyLocks.delete(familyId);
      }
    })();

    this.familyLocks.set(familyId, promise);
    return promise;
  }

  validateGeneratedVariant(variant, familyId) {
    if (!variant || typeof variant.text !== 'string') return false;
    const text = variant.text.trim();
    if (text.length < 10 || text.length > 350) return false;

    // Reject obvious hallucinations, power inventions or contradictions
    const forbidden = [/omniscient/i, /resurrect/i, /spaceship/i, /godlike/i];
    if (forbidden.some(pattern => pattern.test(text))) return false;

    // Reject exact duplicates of existing variants in the family
    const all = this.getAllVariants(familyId);
    if (all.some(v => v.text.toLowerCase() === text.toLowerCase())) return false;

    return true;
  }
}

export function identifyFamily(event) {
  if (!event || !event.type) return null;
  const t = event.type;
  const desc = String(event.description || '').toLowerCase();
  const prose = String(event.prose || '').toLowerCase();
  const text = `${desc} ${prose}`;

  // 1. Supporting stories
  if (t === 'SUPPORTING_COMMITMENT' || t === 'SUPPORTING_ENCOUNTER' || t === 'SUPPORTING_OUTCOME' || t === 'SUPPORTING_CALLBACK') {
    const kind = t === 'SUPPORTING_COMMITMENT' ? 'commitment'
      : t === 'SUPPORTING_ENCOUNTER' ? 'encounter'
      : t === 'SUPPORTING_OUTCOME' ? 'outcome' : 'callback';
    let who = null;
    if (text.includes('henderson')) who = 'henderson';
    else if (text.includes('davis')) who = 'davis';
    else if (text.includes('zara') || text.includes('folder') || text.includes('face down')) who = 'zara';
    else if (text.includes('hammond') || text.includes('chair') || text.includes('seat')) who = 'hammond';
    else if (text.includes('truth')) who = 'truth';
    else if (text.includes('damien')) who = 'damien';
    else if (text.includes('anarchy') || text.includes('balthazar')) who = 'anarchy';
    else if (text.includes('gabriel')) who = 'gabriel';
    else if (text.includes('rose')) who = 'rose';
    else if (text.includes('greah')) who = 'greah';
    else if (text.includes('kai')) who = 'kai';
    if (who) return `supporting:${who}:${kind}`;
  }

  // 2. Ground work & abilities
  if (t === 'GROUND_WORK_OPPORTUNITY') {
    if (text.includes('wet')) return 'ground:opportunity:wet';
    if (text.includes('crew') || text.includes('delay') || text.includes('switched')) return 'ground:opportunity:delayed_crew';
    if (text.includes('preparation') || text.includes('done')) return 'ground:opportunity:prepared';
    return 'ground:opportunity:wet';
  }
  if (t === 'GROUND_RESTRICTION') return 'ground:restriction';
  if (t === 'GROUND_PREPARATION') return 'ground:preparation';
  if (t === 'GROUND_PREPARED') return 'ground:prepared';
  if (t === 'GROUND_WORK_INTERRUPTED') return 'ground:interrupted';
  if (t === 'GROUND_WORK_COMPLETED') return 'ground:completed';

  // 3. Cross paths
  if (t === 'CROSS_PATHS') {
    if (text.includes('lunch hall')) return 'crosspaths:lunch_hall';
    if (text.includes('common room')) return 'crosspaths:common_room';
    if (text.includes('corridor')) return 'crosspaths:corridors';
    return 'crosspaths:lunch_hall';
  }

  // 4. Conversation opening
  if (t === 'CONVERSATION' && event.location === 'mi6') {
    return 'conversation:goaden_ashai';
  }

  // 5. Intentions
  if (t === 'ANNOUNCE_ARRANGEMENT') {
    if (text.includes('sanctuary')) return 'intent:announce:sanctuary';
    return 'intent:announce:game';
  }
  if (t === 'INTENT_OFFER') return 'intent:offer:game';
  if (t === 'INTENT_RESPONSE') return 'intent:response:game';
  if (t === 'INTENT_RENEGOTIATE') return 'intent:renegotiate:quiet';
  if (t === 'INTENT_COMPLETE') return 'intent:complete:game';

  // 6. Agenda & Dispatch
  if (t === 'AGENDA_REPORT_READ') return 'agenda:report_read';
  if (t === 'AGENDA_OPERATION_START') return 'agenda:operation_start';
  if (t === 'AGENDA_REPORT') {
    if (text.includes('matched')) return 'agenda:report:matched';
    return 'agenda:report:partial';
  }
  if (t === 'AGENDA_RELEASE') return 'agenda:release';
  if (t === 'AGENDA_RESOLVE') return 'agenda:resolve:unverified';

  // 7. Offscreen lives
  if (t === 'OFFSCREEN_START') {
    if (text.includes('emily') || event.location === 'big_ben_plaza') return 'offscreen:emily:start';
    if (text.includes('gabriel') || event.location === 'sanctuary') return 'offscreen:gabriel:start';
    if (text.includes('rose') || event.location === 'legion_hideout') return 'offscreen:rose:start';
    if (text.includes('yukon') || event.location === 'mi6') return 'offscreen:yukon:start';
  }
  if (t === 'OFFSCREEN_WITNESS') {
    if (text.includes('emily') || event.location === 'big_ben_plaza') return 'offscreen:emily:witness';
    if (text.includes('gabriel') || event.location === 'sanctuary') return 'offscreen:gabriel:witness';
    if (text.includes('rose') || event.location === 'legion_hideout') return 'offscreen:rose:witness';
  }
  if (t === 'OFFSCREEN_RESULT') {
    if (text.includes('emily') || event.location === 'big_ben_plaza') return 'offscreen:emily:result';
    if (text.includes('gabriel') || event.location === 'sanctuary') return 'offscreen:gabriel:result';
    if (text.includes('rose') || event.location === 'legion_hideout') return 'offscreen:rose:result';
    if (text.includes('yukon') || event.location === 'mi6') return 'offscreen:yukon:result';
  }
  if (t === 'OFFSCREEN_ENCOUNTER') {
    if (text.includes('emily')) return 'offscreen:emily:result';
    if (text.includes('gabriel')) return 'offscreen:gabriel:encounter';
    if (text.includes('rose')) return 'offscreen:rose:result';
    if (text.includes('yukon')) return 'offscreen:yukon:result';
    if (text.includes('zara')) return 'offscreen:zara:encounter';
  }

  // 8. Incidents & Surges
  if (t === 'ARCANE_SURGE') return 'arcane_surge:thames';
  if (t === 'INCIDENT') {
    if (text.includes('alarm')) return 'incident:alarm';
    if (text.includes('courier')) return 'incident:courier';
    return 'incident:alarm';
  }
  if (t === 'AFTERMATH') return 'aftermath:readiness';
  if (t === 'PLAN_CHANGE') return 'plan_change:piano';

  // 9. Night stories
  if (t === 'NIGHT_RECOVERED' || t === 'NIGHT_RETURN') return 'night:check_over';
  if (t === 'NIGHT_CALL') return 'night:call';

  // 10. Venues & travel
  if (t === 'VENUE_SCENE') {
    if (event.location === 'cafe') return 'venue:cafe';
    if (event.location === 'enchanted_ink') return 'venue:enchanted_ink';
  }
  if (t === 'TRAVEL_ARRIVE' && text.includes('cafe')) return 'travel:cafe';
  if (t === 'QUIET_TIME_BEGIN') return 'quiet_break:ashai';

  return null;
}

