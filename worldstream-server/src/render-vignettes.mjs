import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { openStartupWorld } from './startup-world.mjs';
import { RULES_VERSION } from './fixture.mjs';
import { londonDate } from './time.mjs';
import { canonicalBrief, briefKey, renderVignette, PROMPT_VERSION } from './presentation.mjs';

// The Phase C runner, and deliberately a separate program rather than anything
// the server does while a visitor waits. It reads a world that has already been
// committed, writes prose beside it, and never writes back into it. Deleting
// every file it produces loses nothing but the prose.
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const cacheDirectory = join(root,'artifacts','vignettes',RULES_VERSION,PROMPT_VERSION);

// One rendering per event, kept forever. The point is not to save money — it is
// that a day a reader has already read must not quietly rewrite itself the next
// time somebody looks at it. A vignette is generated once and then it is what
// happened, in the same way the event under it is.
const cachePath = key => join(cacheDirectory,`${key}.json`);
export function readCache(key) {
  const path=cachePath(key);
  if(!existsSync(path)) return null;
  try { return JSON.parse(readFileSync(path,'utf8')); } catch { return null; }
}
export function writeCache(key,record) {
  mkdirSync(cacheDirectory,{recursive:true});
  writeFileSync(cachePath(key),`${JSON.stringify(record,null,2)}\n`);
}

// Render every public event of one London day. Events already rendered are read
// from the cache; only genuinely new ones reach a model.
// The cache is injectable so a test can exercise this without writing prose
// into the project's own artifacts directory, and so a caller can render a day
// twice without a warm cache masking what the second run actually did.
export const fileCache = Object.freeze({read:readCache,write:writeCache});
export const memoryCache = () => {const store=new Map();
  return {read:key=>store.get(key)??null,write:(key,record)=>store.set(key,record)};};
export async function renderDay({projection,day,client,limit=40,onReject,cache=fileCache}={}) {
  const events=projection.events.filter(event=>londonDate(event.occurredAt)===day).slice(-limit);
  const rendered=[];
  for(const event of events) {
    const brief=canonicalBrief(event,projection), key=briefKey(brief);
    const cached=cache.read(key);
    if(cached) { rendered.push({...cached,cached:true}); continue; }
    const result=await renderVignette(brief,{client,onReject});
    const record={key,eventId:brief.eventId,occurredAt:brief.occurredAt,londonTime:brief.londonTime,
      fact:brief.fact,prose:result.prose,source:result.source,reason:result.reason,
      rulesVersion:RULES_VERSION,promptVersion:PROMPT_VERSION};
    // Only a real rendering is worth keeping. Caching a fallback would freeze a
    // transient network failure into the record permanently.
    if(result.source==='model') cache.write(key,record);
    rendered.push({...record,cached:false});
  }
  return rendered;
}

export function toMarkdown(day,rendered) {
  const lines=[`# Silver Clouds — ${day}`,'',
    '> Presentation layer. Every canonical fact below was decided and committed by the',
    '> deterministic engine before any of this prose existed; the prose restates it and',
    '> nothing more. Where a rendering was refused, the canonical sentence stands.','',];
  for(const item of rendered) {
    lines.push(`### ${item.londonTime}`,'',item.prose,'');
    if(item.source!=='model') lines.push(`> canonical — ${item.reason??'not rendered'}`,'');
    else lines.push(`> fact: ${item.fact}`,'');
  }
  return `${lines.join('\n')}\n`;
}

export async function main(argv=process.argv.slice(2)) {
  const dbPath=join(root,'data',`world-${RULES_VERSION}.sqlite`);
  if(!existsSync(dbPath)) { process.stderr.write(`No world at ${dbPath}. Run the server once first.\n`); process.exitCode=1; return; }
  const world=openStartupWorld({dbPath});
  try {
    const projection=world.publicProjection();
    const day=argv[0]??londonDate(projection.resolvedThrough);
    // The live viewer gate owns new provider calls. This legacy command is
    // still useful as a canonical/cached archive export for the author.
    const client=null;
    process.stdout.write('Archive export only. New prose is generated by the live Worldstream viewer gate.\n');
    const rejects=[];
    const rendered=await renderDay({projection,day,client,onReject:item=>rejects.push(item)});
    if(!rendered.length) { process.stdout.write(`No public events on ${day}.\n`); return; }
    const outputDirectory=join(root,'artifacts','vignettes',RULES_VERSION,PROMPT_VERSION,'days');
    mkdirSync(outputDirectory,{recursive:true});
    const outputPath=join(outputDirectory,`${day}.md`);
    writeFileSync(outputPath,toMarkdown(day,rendered));
    const byModel=rendered.filter(item=>item.source==='model').length;
    process.stdout.write(`${day}: ${rendered.length} events, ${byModel} rendered, ${rendered.length-byModel} canonical.\n`);
    for(const reject of rejects) process.stdout.write(`  refused (${reject.reason}): ${reject.prose.slice(0,80)}\n`);
    process.stdout.write(`${outputPath}\n`);
  } finally { world.close(); }
}

const isMain = process.argv[1] && import.meta.url===pathToFileURL(resolve(process.argv[1])).href;
if(isMain) await main();
